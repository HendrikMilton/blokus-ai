"""
Supervised training for Blokus AI.

Trains a BlokusNet neural network on heuristic policy targets from Expert
games (generated by supervised_data.py), replacing the failed AlphaZero
cold-start approach.

Usage:
    python -m app.features.alphazero.supervised_trainer --num-games 5000 --epochs 100
"""

import os
import time
import random
from typing import List, Tuple, Optional
from dataclasses import dataclass

import numpy as np
import torch
import torch.nn.functional as F
import torch.optim as optim
from torch.amp import autocast, GradScaler

from app.logging_config import log
from .network import create_network, BlokusNet
from .pretraining import compute_policy_cross_entropy
from .self_play import TrainingExample


@dataclass
class SupervisedConfig:
    # Data generation
    num_games: int = 5000

    # Training
    batch_size: int = 4096
    epochs: int = 100
    learning_rate: float = 0.002
    value_loss_weight: float = 1.0
    mixed_precision: bool = True
    max_grad_norm: float = 1.0

    # Model
    num_res_blocks: int = 15
    channels: int = 256

    # Evaluation
    eval_interval: int = 20      # Evaluate every N epochs
    eval_games: int = 20         # Games vs Expert for eval

    # Paths
    save_dir: str = "models/supervised"
    data_path: Optional[str] = None  # Path to pre-generated dataset

    # Split
    train_val_split: float = 0.9


class SupervisedTrainer:
    def __init__(self, config: SupervisedConfig):
        self.config = config
        self.device = 'cuda' if torch.cuda.is_available() else 'cpu'

        # Create network
        self.network = create_network(
            num_res_blocks=config.num_res_blocks,
            channels=config.channels,
            device=self.device,
        )

        # Optimizer
        self.optimizer = optim.Adam(self.network.parameters(), lr=config.learning_rate)

        # LR scheduler: cosine annealing over all epochs
        self.scheduler = optim.lr_scheduler.CosineAnnealingLR(
            self.optimizer, T_max=config.epochs
        )

        # Mixed precision
        self.scaler = GradScaler('cuda') if config.mixed_precision and self.device == 'cuda' else None

        # Tracking
        self.best_val_loss = float('inf')
        self.best_eval_win_rate = 0.0

    def train(self):
        # 1. Load or generate data
        if self.config.data_path and os.path.exists(self.config.data_path):
            from .supervised_data import load_dataset
            examples = load_dataset(self.config.data_path)
        else:
            from .supervised_data import generate_training_examples, save_dataset
            examples = generate_training_examples(self.config.num_games)
            if self.config.data_path:
                save_dataset(examples, self.config.data_path)

        log.info(f"Dataset: {len(examples)} examples")

        # 2. Split train/val
        random.shuffle(examples)
        split_idx = int(len(examples) * self.config.train_val_split)
        train_examples = examples[:split_idx]
        val_examples = examples[split_idx:]

        log.info(f"Train: {len(train_examples)}, Val: {len(val_examples)}")

        # 3. Save dir
        os.makedirs(self.config.save_dir, exist_ok=True)

        # 4. Training loop
        for epoch in range(1, self.config.epochs + 1):
            train_policy_loss, train_value_loss = self._train_epoch(train_examples)

            # Step scheduler
            self.scheduler.step()

            # Log
            log.info(f"Epoch {epoch}/{self.config.epochs} - "
                    f"policy_loss: {train_policy_loss:.4f}, "
                    f"value_loss: {train_value_loss:.4f}, "
                    f"lr: {self.scheduler.get_last_lr()[0]:.6f}")

            # Validation
            val_policy_loss, val_value_loss = self._validate(val_examples)
            log.info(f"  Val - policy_loss: {val_policy_loss:.4f}, value_loss: {val_value_loss:.4f}")

            # Save checkpoint if best val loss
            total_val_loss = val_policy_loss + self.config.value_loss_weight * val_value_loss
            if total_val_loss < self.best_val_loss:
                self.best_val_loss = total_val_loss
                self._save_checkpoint(epoch, train_policy_loss, train_value_loss,
                                     self.best_eval_win_rate, is_best=True)

            # Save periodic checkpoint
            if epoch % 10 == 0:
                self._save_checkpoint(epoch, train_policy_loss, train_value_loss,
                                     self.best_eval_win_rate, is_best=False)

            # Evaluate vs Expert
            if epoch % self.config.eval_interval == 0:
                eval_results = self.evaluate_vs_expert(num_games=self.config.eval_games)
                log.info(f"  Eval vs Expert - win_rate: {eval_results['win_rate']:.1%}, "
                        f"avg_score: {eval_results['avg_score']:.1f}")
                if eval_results['win_rate'] > self.best_eval_win_rate:
                    self.best_eval_win_rate = eval_results['win_rate']
                    self._save_checkpoint(epoch, train_policy_loss, train_value_loss,
                                         eval_results['win_rate'], is_best=True)

    def _train_epoch(self, examples: List[TrainingExample]) -> Tuple[float, float]:
        self.network.train()

        total_policy_loss = 0.0
        total_value_loss = 0.0
        num_batches = 0

        # Shuffle and iterate in batches
        indices = list(range(len(examples)))
        random.shuffle(indices)

        for start in range(0, len(indices), self.config.batch_size):
            batch_indices = indices[start:start + self.config.batch_size]
            batch = [examples[i] for i in batch_indices]

            policy_loss, value_loss = self._train_batch(batch)
            total_policy_loss += policy_loss
            total_value_loss += value_loss
            num_batches += 1

        return total_policy_loss / num_batches, total_value_loss / num_batches

    def _train_batch(self, batch: List[TrainingExample]) -> Tuple[float, float]:
        # Prepare tensors
        board_np = np.stack([ex.board_tensor for ex in batch])
        pieces_np = np.stack([ex.pieces_vector for ex in batch])
        values_np = np.array([ex.value for ex in batch], dtype=np.float32)

        board_tensors = torch.from_numpy(board_np).to(self.device)
        pieces_vectors = torch.from_numpy(pieces_np).to(self.device)
        target_values = torch.from_numpy(values_np).to(self.device)

        # Legal moves as list of lists of tuples (piece_idx, orient_idx, row, col)
        legal_moves_list = [
            [(m.piece_idx, m.orientation_idx, m.row, m.col) for m in ex.legal_moves]
            for ex in batch
        ]

        # Build batch dicts for compute_policy_cross_entropy
        batch_dicts = [{'target_policy': ex.policy} for ex in batch]

        self.optimizer.zero_grad()

        if self.scaler:
            with autocast('cuda'):
                policy_logits, value_pred = self.network(board_tensors, pieces_vectors, legal_moves_list)
                policy_loss = compute_policy_cross_entropy(policy_logits, batch_dicts, self.device)
                value_loss = F.mse_loss(value_pred.squeeze(-1), target_values)
                total_loss = policy_loss + self.config.value_loss_weight * value_loss

            self.scaler.scale(total_loss).backward()
            self.scaler.unscale_(self.optimizer)
            torch.nn.utils.clip_grad_norm_(self.network.parameters(), self.config.max_grad_norm)
            self.scaler.step(self.optimizer)
            self.scaler.update()
        else:
            policy_logits, value_pred = self.network(board_tensors, pieces_vectors, legal_moves_list)
            policy_loss = compute_policy_cross_entropy(policy_logits, batch_dicts, self.device)
            value_loss = F.mse_loss(value_pred.squeeze(-1), target_values)
            total_loss = policy_loss + self.config.value_loss_weight * value_loss

            total_loss.backward()
            torch.nn.utils.clip_grad_norm_(self.network.parameters(), self.config.max_grad_norm)
            self.optimizer.step()

        return policy_loss.item(), value_loss.item()

    def _validate(self, examples: List[TrainingExample]) -> Tuple[float, float]:
        self.network.eval()

        total_policy_loss = 0.0
        total_value_loss = 0.0
        num_batches = 0

        with torch.no_grad():
            for start in range(0, len(examples), self.config.batch_size):
                batch = examples[start:start + self.config.batch_size]

                board_np = np.stack([ex.board_tensor for ex in batch])
                pieces_np = np.stack([ex.pieces_vector for ex in batch])
                values_np = np.array([ex.value for ex in batch], dtype=np.float32)

                board_tensors = torch.from_numpy(board_np).to(self.device)
                pieces_vectors = torch.from_numpy(pieces_np).to(self.device)
                target_values = torch.from_numpy(values_np).to(self.device)

                legal_moves_list = [
                    [(m.piece_idx, m.orientation_idx, m.row, m.col) for m in ex.legal_moves]
                    for ex in batch
                ]

                batch_dicts = [{'target_policy': ex.policy} for ex in batch]

                policy_logits, value_pred = self.network(board_tensors, pieces_vectors, legal_moves_list)
                policy_loss = compute_policy_cross_entropy(policy_logits, batch_dicts, self.device)
                value_loss = F.mse_loss(value_pred.squeeze(-1), target_values)

                total_policy_loss += policy_loss.item()
                total_value_loss += value_loss.item()
                num_batches += 1

        self.network.train()

        return total_policy_loss / num_batches, total_value_loss / num_batches

    def evaluate_vs_expert(self, num_games: int = 20) -> dict:
        """Play NN (argmax policy, no MCTS) vs 3 SmartPlayer Expert opponents."""
        from .smart_player import SmartPlayer, SmartPlayerConfig
        from .game import BlokusGame

        self.network.eval()

        wins = 0
        total_score = 0
        total_pieces = 0

        for game_idx in range(num_games):
            game = BlokusGame()
            nn_player = game_idx % 4  # Rotate NN position for fairness
            experts = {i: SmartPlayer(SmartPlayerConfig.expert()) for i in range(4) if i != nn_player}

            while not game.is_game_over:
                legal_moves = game.get_legal_moves()
                if not legal_moves:
                    game.pass_turn()
                    continue

                if game.current_player == nn_player:
                    # NN move: argmax policy
                    board_tensor, pieces_vector = game.get_state_for_neural_net()
                    move_tuples = [(m.piece_idx, m.orientation_idx, m.row, m.col) for m in legal_moves]

                    with torch.no_grad():
                        bt = torch.from_numpy(board_tensor).unsqueeze(0).to(self.device)
                        pv = torch.from_numpy(pieces_vector).unsqueeze(0).to(self.device)
                        policy_logits, _ = self.network(bt, pv, [move_tuples])
                        # Argmax
                        best_idx = policy_logits[0, :len(legal_moves)].argmax().item()

                    move = legal_moves[best_idx]
                else:
                    move = experts[game.current_player].select_move(game)

                if move:
                    game.make_move(move)
                else:
                    game.pass_turn()

            scores = game.get_scores()
            nn_score = scores[nn_player]
            total_score += nn_score

            # Count pieces placed by NN
            nn_pieces = 21 - len(game.players[nn_player].remaining_pieces)
            total_pieces += nn_pieces

            if game.get_winner() == nn_player:
                wins += 1

        self.network.train()

        return {
            'win_rate': wins / num_games,
            'avg_score': total_score / num_games,
            'avg_pieces_placed': total_pieces / num_games,
        }

    def _save_checkpoint(self, epoch, policy_loss, value_loss, eval_win_rate, is_best=False):
        checkpoint = {
            'generation': 0,  # supervised
            'step': epoch,
            'model_state_dict': self.network.state_dict(),
            'optimizer_state_dict': self.optimizer.state_dict(),
            'policy_loss': policy_loss,
            'value_loss': value_loss,
            'eval_win_rate': eval_win_rate,
            'heuristic_win_rate': 0.0,
            'config': {
                'num_res_blocks': self.config.num_res_blocks,
                'channels': self.config.channels,
            },
        }

        path = os.path.join(self.config.save_dir, f"epoch_{epoch}.pt")
        torch.save(checkpoint, path)
        log.info(f"Saved checkpoint: {path}")

        if is_best:
            best_path = os.path.join(self.config.save_dir, "best.pt")
            torch.save(checkpoint, best_path)
            log.info(f"Saved best checkpoint: {best_path}")


